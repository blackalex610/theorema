def seed_curriculum():
    """Seed complete curriculum structure"""
    db = SessionLocal()
    
    try:
        # Clear existing data
        print("\n🗑️  Clearing existing data...")
        db.query(Exercise).delete()
        db.query(Lesson).delete()
        db.query(Topic).delete()
        db.query(Grade).delete()
        db.commit()
        print("✓ Database cleared\n")
        
        # Create grades and populate curriculum
        print("📚 Creating curriculum...")
        for grade_num in [5, 6, 7]:
            grade = Grade(grade_number=grade_num)
            db.add(grade)
            db.commit()  # Commit to get ID
            
            for topic_data in CURRICULUM_DATA[grade_num]:
                topic = Topic(
                    grade_id=grade.id,
                    title=topic_data["title"],
                    description=topic_data["description"]
                )
                db.add(topic)
                db.commit()  # Commit to get ID
                
                # Add lessons for this topic
                for lesson_title in topic_data["lessons"]:
                    lesson = Lesson(
                        topic_id=topic.id,
                        title=lesson_title
                    )
                    db.add(lesson)
                
                db.commit()
        
        # Verify and report
        grade_5_topics = db.query(Topic).filter(Topic.grade_id == 1).count()
        grade_6_topics = db.query(Topic).filter(Topic.grade_id == 2).count()
        grade_7_topics = db.query(Topic).filter(Topic.grade_id == 3).count()
        total_lessons = db.query(Lesson).count()
        
        print("=" * 60)
        print("✅ CURRICULUM SUCCESSFULLY CREATED")
        print("=" * 60)
        print(f"Grade 5: {grade_5_topics} topics")
        print(f"Grade 6: {grade_6_topics} topics")
        print(f"Grade 7: {grade_7_topics} topics")
        print(f"Total: {grade_5_topics + grade_6_topics + grade_7_topics} topics, {total_lessons} lessons")
        print("=" * 60)
        print("\nAll lessons are ready for content addition!")
        
    except Exception as e:
        print(f"❌ Error: {str(e)}")
        db.rollback()
        raise
    finally:
        db.close()


if __name__ == "__main__":
    create_tables()
    seed_curriculum()
